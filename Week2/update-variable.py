def main():
    # Augmented Assignment Operator

    score = 10
    # score2 = score + 10. This and the one below is the same just simpler.
    score += 10
    print(score)

    # Substraction Assignment Operator

    grade = 100
    grade -= 15
    print(grade)

    # Multiplication Assignment Operator

    balance = 10
    balance *= 4
    print(balance)

    # Division Assignment Operator

    x = 10
    x /=5
    print(x)

    # Modulus Assignment Operator
    
    a = 10
    b = 4

    a %= b
    print(a)

if __name__=="__main__":
    main()
